"""The job that renders the paper's figures with LaTeX and compiles the paper, on the cluster
(PI, 2026-10-29: no figure rendering or compiling on the laptop).

At a pushed commit, in the v2 image: installs TeX Live (LaTeX, the Computer Modern Type 1
fonts and dvipng, so matplotlib's text.usetex typesets every label), pins matplotlib and
mplhep to the versions the figure code was written against, draws the paper's and the deck's
figures (experiments/FIGS/mlst_figures.py, deck_figures.py) from the committed data, compiles
paper/journal/main.tex with tectonic, and copies the figures, the PDF and the logs to
/data/results/render/<commit>/. CPU only; backoffLimit 0 (a failure is read, not retried).

    python3 scripts/build_render_job.py            # the spec for HEAD, which must be pushed
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "experiments" / "FIGS" / "k8s"
IMAGE = ("gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning@sha256:"
         "db235b515a278198ebc6dc2c607c9c38cfb10e6b46e29ed2847ec9f4af6191e7")
TECTONIC = ("https://github.com/tectonic-typesetting/tectonic/releases/download/"
            "tectonic%400.15.0/tectonic-0.15.0-x86_64-unknown-linux-musl.tar.gz")
PINS = "matplotlib==3.10.7 mplhep==0.4.1"     # the laptop's, where the figure code was written

SPEC = """apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_render_job.py: figures with LaTeX and the compiled paper at
  # commit {short}, into /data/results/render/{short}/. CPU only.
  name: render-{short}-raunav
  namespace: cms-ml
spec:
  backoffLimit: 0
  activeDeadlineSeconds: 7200
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {image}
        command: ["/bin/bash", "-c"]
        env:
        - name: COMMIT
          value: "{commit}"
        args:
        - |
          set -uo pipefail
          OUT=/data/results/render/${{COMMIT:0:7}}
          USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
          [ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data is ${{USED}}% full"; exit 42; }}
          mkdir -p ${{OUT}}
          git clone -q https://github.com/raunavm/transferlearningsophon.git /workspace/repo || exit 1
          cd /workspace/repo && git checkout -q ${{COMMIT}} || exit 1
          export DEBIAN_FRONTEND=noninteractive
          (apt-get update -qq && apt-get install -y -qq --no-install-recommends texlive-latex-base \\
             texlive-latex-extra texlive-fonts-recommended cm-super dvipng) > ${{OUT}}/apt.txt 2>&1 \\
             || {{ echo "FATAL: TeX Live did not install"; tail -5 ${{OUT}}/apt.txt; exit 1; }}
          pip install --no-cache-dir -q {pins} pyarrow || exit 1
          latex --version | head -1
          python3 experiments/FIGS/mlst_figures.py > ${{OUT}}/figures.txt 2>&1; echo "figures rc=$?"
          python3 experiments/FIGS/deck_figures.py > ${{OUT}}/deck_figures.txt 2>&1; echo "deck figures rc=$?"
          tail -5 ${{OUT}}/figures.txt ${{OUT}}/deck_figures.txt
          mkdir -p /workspace/tectonic && python3 -c "import urllib.request,sys; urllib.request.urlretrieve(sys.argv[1], '/workspace/tectonic/t.tgz')" \\
            "{tectonic}" && tar -xzf /workspace/tectonic/t.tgz -C /workspace/tectonic \\
            && (cd paper/journal && /workspace/tectonic/tectonic -X compile main.tex > ${{OUT}}/tectonic.txt 2>&1; echo "tectonic rc=$?") \\
            || echo "tectonic: could not fetch or run"
          grep -i -E 'undefined|multiply defined|error|overfull' ${{OUT}}/tectonic.txt | head -20
          mkdir -p ${{OUT}}/figures ${{OUT}}/deck
          cp -f figures/*.pdf figures/*.png ${{OUT}}/figures/ 2>/dev/null
          cp -f figures/deck/* ${{OUT}}/deck/ 2>/dev/null
          cp -f paper/journal/main.pdf ${{OUT}}/main.pdf 2>/dev/null
          pdffonts ${{OUT}}/main.pdf 2>/dev/null | grep -c "Type 3" | sed 's/^/Type 3 fonts in the PDF: /'
          ls -la ${{OUT}} ${{OUT}}/figures | head -40
          echo "RENDER COMPLETE"
        resources:
          requests: {{ memory: "16Gi", cpu: "4", ephemeral-storage: "20Gi" }}
          limits:   {{ memory: "16Gi", cpu: "4", ephemeral-storage: "20Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
"""


def main() -> int:
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                            text=True, check=True).stdout.strip()
    remote = subprocess.run(["git", "branch", "-r", "--contains", commit], cwd=ROOT,
                            capture_output=True, text=True).stdout
    if "origin/main" not in remote:
        raise SystemExit(f"FATAL: {commit[:7]} is not pushed; the pod clones it from GitHub")
    out = OUT_DIR / f"job-render-{commit[:7]}-raunav.yaml"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out.write_text(SPEC.format(short=commit[:7], commit=commit, image=IMAGE, pins=PINS, tectonic=TECTONIC))
    print(out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
