"""The job that renders the paper's figures with LaTeX and compiles the paper, on the cluster
(PI, 2026-10-29: no figure rendering or compiling on the laptop).

At a pushed commit, in the v2 image: installs TeX Live (LaTeX, dvipng, the Type 1 fonts with
Helvetica, and the helvet and sansmath packages, so matplotlib's text.usetex typesets every label
in Helvetica: experiments/FIGS/mlst_style.py), pins matplotlib and mplhep to the versions the
figure code was written against, writes the paper's numbers and tables from the committed data
(experiments/FIGS/make_tables.py: paper/journal/results_generated.tex, provenance.json, tables/),
draws the paper's figures (experiments/FIGS/paper_figures.py, into figures/mlst/, and the approved
gallery figures, experiments/FIGS/figstyle/gallery_figures.py --paper, into figures/mlst/gallery/), compiles
paper/journal/main.tex with tectonic, and copies the generated files (at their paths in the
repository), the PDF and the logs to /data/results/render/<commit>/. CPU only; backoffLimit 0 (a
failure is read, not retried).

    python3 scripts/build_render_job.py            # the spec for HEAD, which must be pushed
    python3 scripts/build_render_job.py --mockups  # the figure mock-ups (experiments/FIGS/mockup_figures.py,
                                                   # paper/mockups/mockups.tex) into render/<commit>-mockups/
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "experiments" / "FIGS" / "k8s"
IMAGE = ("gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning@sha256:"
         "db235b515a278198ebc6dc2c607c9c38cfb10e6b46e29ed2847ec9f4af6191e7")
TECTONIC = ("https://github.com/tectonic-typesetting/tectonic/releases/download/"
            "tectonic%400.15.0/tectonic-0.15.0-x86_64-unknown-linux-musl.tar.gz")
PINS = "matplotlib==3.10.7 mplhep==0.4.1"     # the laptop's, where the figure code was written

SPEC = """apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_render_job.py: figures with LaTeX and the compiled {what} at
  # commit {short}, into /data/results/render/{short}{suffix}/. CPU only.
  name: render{suffix}-{short}-raunav
  namespace: cms-ml
spec:
  backoffLimit: 0
  activeDeadlineSeconds: 7200
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {image}
        command: ["/bin/bash", "-c"]
        env:
        - name: COMMIT
          value: "{commit}"
        args:
        - |
          set -uo pipefail
          OUT=/data/results/render/${{COMMIT:0:7}}{suffix}
          USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
          [ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data is ${{USED}}% full"; exit 42; }}
          mkdir -p ${{OUT}}
          git clone -q https://github.com/raunavm/transferlearningsophon.git /workspace/repo || exit 1
          cd /workspace/repo && git checkout -q ${{COMMIT}} || exit 1
          export DEBIAN_FRONTEND=noninteractive
          (apt-get update -qq && apt-get install -y -qq --no-install-recommends texlive-latex-base \\
             texlive-latex-extra texlive-fonts-recommended cm-super dvipng) > ${{OUT}}/apt.txt 2>&1 \\
             || {{ echo "FATAL: TeX Live did not install"; tail -5 ${{OUT}}/apt.txt; exit 1; }}
          pip install --no-cache-dir -q {pins} pyarrow || exit 1
          latex --version | head -1
{draw}          mkdir -p /workspace/tectonic && python3 -c "import urllib.request,sys; urllib.request.urlretrieve(sys.argv[1], '/workspace/tectonic/t.tgz')" \\
            "{tectonic}" && tar -xzf /workspace/tectonic/t.tgz -C /workspace/tectonic \\
            && (cd {texdir} && /workspace/tectonic/tectonic -X compile {texfile}.tex > ${{OUT}}/tectonic.txt 2>&1; echo "tectonic rc=$?") \\
            || echo "tectonic: could not fetch or run"
          grep -i -E 'undefined|multiply defined|error|overfull' ${{OUT}}/tectonic.txt | head -20
{collect}          pdffonts ${{OUT}}/{texfile}.pdf 2>/dev/null | grep -c "Type 3" | sed 's/^/Type 3 fonts in the PDF: /'
          ls -la ${{OUT}} ${{OUT}}/figures | head -40
          echo "RENDER COMPLETE"
        resources:
          requests: {{ memory: "16Gi", cpu: "4", ephemeral-storage: "20Gi" }}
          limits:   {{ memory: "16Gi", cpu: "4", ephemeral-storage: "20Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
"""


# the paper: its numbers and tables, then its figures, then main.tex; the generated files are
# collected at their paths in the repository, so they copy back as they are
PAPER = {"what": "paper", "suffix": "", "texdir": "paper/journal", "texfile": "main",
         "draw": """          python3 experiments/FIGS/make_tables.py > ${OUT}/tables.txt 2>&1; echo "tables rc=$?"
          python3 experiments/FIGS/paper_figures.py > ${OUT}/figures.txt 2>&1; echo "figures rc=$?"
          python3 experiments/FIGS/figstyle/gallery_figures.py --paper --outdir figures/mlst/gallery > ${OUT}/gallery.txt 2>&1; echo "gallery rc=$?"
          tail -15 ${OUT}/tables.txt ${OUT}/figures.txt ${OUT}/gallery.txt
""",
         "collect": """          mkdir -p ${OUT}/figures/mlst ${OUT}/paper/journal
          cp -f figures/mlst/*.pdf figures/mlst/*.png ${OUT}/figures/mlst/ 2>/dev/null
          mkdir -p ${OUT}/figures/mlst/gallery && cp -f figures/mlst/gallery/* ${OUT}/figures/mlst/gallery/ 2>/dev/null
          cp -f paper/journal/results_generated.tex paper/journal/provenance.json ${OUT}/paper/journal/ 2>/dev/null
          cp -rf paper/journal/tables paper/journal/data_release ${OUT}/paper/journal/ 2>/dev/null
          cp -f paper/journal/main.pdf ${OUT}/main.pdf 2>/dev/null
"""}
# the X->bb/X->bs dry run on JetClass-II stand-in jets (RUNS.csv), the mock-up of the resonance figure
XBX_STANDIN = "/data/results/xbx_dryrun/report_mtx-s2.28/xbx.pdf"
MOCKUPS = {"what": "figure mock-ups", "suffix": "-mockups", "texdir": "paper/mockups", "texfile": "mockups",
           "draw": f"""          python3 experiments/FIGS/mockup_figures.py --outdir figures/mockups > ${{OUT}}/figures.txt 2>&1; echo "mock-ups rc=$?"
          tail -15 ${{OUT}}/figures.txt
          cp -f {XBX_STANDIN} figures/mockups/F9_xbx_standin.pdf || echo "no X->bx stand-in at {XBX_STANDIN}"
""",
           "collect": """          mkdir -p ${OUT}/figures
          cp -f figures/mockups/*.pdf figures/mockups/*.png ${OUT}/figures/ 2>/dev/null
          cp -f paper/mockups/mockups.pdf ${OUT}/mockups.pdf 2>/dev/null
"""}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mockups", action="store_true", help="the figure mock-ups instead of the paper")
    mode = MOCKUPS if ap.parse_args().mockups else PAPER
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                            text=True, check=True).stdout.strip()
    remote = subprocess.run(["git", "branch", "-r", "--contains", commit], cwd=ROOT,
                            capture_output=True, text=True).stdout
    if "origin/main" not in remote:
        raise SystemExit(f"FATAL: {commit[:7]} is not pushed; the pod clones it from GitHub")
    out = OUT_DIR / f"job-render{mode['suffix']}-{commit[:7]}-raunav.yaml"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out.write_text(SPEC.format(short=commit[:7], commit=commit, image=IMAGE, pins=PINS, tectonic=TECTONIC, **mode))
    print(out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
