#!/usr/bin/env python3
"""A CPU job that runs pytest at one commit on the cluster (tests run there, never on the laptop).

    python3 scripts/build_test_job.py --commit <sha> --label kin tests/test_kin_arms.py ...
    python3 scripts/build_test_job.py --commit <sha> --label full --full

Writes experiments/MTX/k8s/v2/tests/job-mtx2-tests-<label>-<sha7>-raunav.yaml. The pod clones the
repository at the commit, installs pytest and the figure pins, runs the named test files (or, with
--full, tests/ and src/stats/tests/), and writes the log to /data/results/tests/<sha7>-<label>/.
The last line of its log is TESTS COMPLETE.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "experiments" / "MTX" / "k8s" / "v2" / "tests"
IMAGE = ("gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning@"
         "sha256:db235b515a278198ebc6dc2c607c9c38cfb10e6b46e29ed2847ec9f4af6191e7")


def spec(commit: str, label: str, tests: list, full: bool) -> tuple:
    name = f"mtx2-tests-{label}-{commit[:7]}-raunav"
    if len(name) > 63:
        raise SystemExit(f"{name}: longer than a Kubernetes name allows")
    target = "tests/ src/stats/tests/" if full else " ".join(tests)
    return name, f"""apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_test_job.py -- pytest at {commit[:7]} ({label}).
  name: {name}
  namespace: cms-ml
spec:
  backoffLimit: 0
  activeDeadlineSeconds: 21600
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {IMAGE}
        command: ["/bin/bash", "-c"]
        env:
        - name: COMMIT
          value: "{commit}"
        - name: NODE_NAME
          valueFrom: {{ fieldRef: {{ fieldPath: spec.nodeName }} }}
        args:
        - |
          set -uo pipefail
          OUT=/data/results/tests/${{COMMIT:0:7}}-{label}
          USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
          echo "PVC used: ${{USED}}%  node: ${{NODE_NAME}}"
          [ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data is ${{USED}}% full"; exit 42; }}
          mkdir -p ${{OUT}}
          git clone -q https://github.com/raunavm/transferlearningsophon.git /workspace/repo || exit 1
          cd /workspace/repo && git checkout -q ${{COMMIT}} || exit 1
          git rev-parse HEAD
          pip install --no-cache-dir -q pytest pyarrow matplotlib==3.10.7 mplhep==0.4.1 || exit 1
          python3 -c "import sys, torch, weaver; print(sys.version.split()[0], torch.__version__, weaver.__file__)"
          python3 -m pytest {target} -q -p no:cacheprovider -rfE > ${{OUT}}/pytest.txt 2>&1
          echo "pytest rc=$?"
          grep -E '^(FAILED|ERROR) ' ${{OUT}}/pytest.txt | cut -c1-400 | head -300
          tail -3 ${{OUT}}/pytest.txt
          echo "TESTS COMPLETE"
        resources:
          requests: {{ memory: "32Gi", cpu: "8", ephemeral-storage: "20Gi" }}
          limits:   {{ memory: "32Gi", cpu: "8", ephemeral-storage: "20Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
        - {{ name: dshm, mountPath: /dev/shm }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
      - name: dshm
        emptyDir: {{ medium: Memory, sizeLimit: "4Gi" }}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", required=True)
    ap.add_argument("--label", required=True)
    ap.add_argument("--full", action="store_true")
    ap.add_argument("tests", nargs="*")
    a = ap.parse_args(argv)
    if not a.full and not a.tests:
        ap.error("name test files or pass --full")
    name, text = spec(a.commit, a.label, a.tests, a.full)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"job-{name}.yaml"
    path.write_text(text)
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
