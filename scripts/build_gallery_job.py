#!/usr/bin/env python3
"""The CPU job that draws the figure gallery's mock-ups at the pushed HEAD into
/data/results/render/<commit>-gallery/ (experiments/FIGS/figstyle/gallery_figures.py).

    python3 scripts/build_gallery_job.py [--storage-line 90]
"""
import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import storage_line  # noqa: E402
OUT_DIR = ROOT / "experiments" / "FIGS" / "k8s"
IMAGE = "gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning:cu121"
SPEC = """apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_gallery_job.py: the gallery's mock-ups at commit {short}. CPU only.
  name: render-gallery-{short}-raunav
  namespace: cms-ml
spec:
  backoffLimit: 0
  activeDeadlineSeconds: 3600
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {image}
        command: ["/bin/bash", "-c"]
        args:
        - |
          set -uo pipefail
          OUT=/data/results/render/{short}-gallery
          USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
          [ "${{USED}}" -le {line} ] || {{ echo "FATAL: /data is ${{USED}}% full"; exit 42; }}
          mkdir -p ${{OUT}}/figures
          for T in 1 2 3 4 5; do git clone -q https://github.com/raunavm/transferlearningsophon.git /workspace/repo && break; sleep 30; done
          cd /workspace/repo && git checkout -q {commit} || exit 1
          pip install --no-cache-dir -q matplotlib==3.10.7 mplhep==0.4.1 pyarrow pymupdf==1.26.7 || exit 1
          python3 experiments/FIGS/figstyle/gallery_figures.py --outdir ${{OUT}}/figures 2>&1 | tee ${{OUT}}/figures.txt
          # the measured checklist of every drawn page (figcheck: fonts, overlaps, points outside the axes, ...)
          IDS=$(python3 -c "import json,sys;print(' '.join(p['id'] for p in json.load(open(sys.argv[1])) if p['drawn'] and p['id'] not in ('INVENTORY','PALETTE','SOPHON-FIG2')))" ${{OUT}}/figures/pages.json)
          python3 experiments/FIGS/figstyle/figcheck.py --outdir /tmp/check --only ${{IDS}} > ${{OUT}}/check.txt 2>&1 || echo "figcheck rc=$?" >> ${{OUT}}/check.txt
          (cd ${{OUT}} && tar czf out.tgz figures figures.txt check.txt)
          ls -la ${{OUT}}/figures | head -60
          echo "RENDER COMPLETE"
        resources:
          requests: {{ memory: "12Gi", cpu: "2", ephemeral-storage: "5Gi" }}
          limits:   {{ memory: "12Gi", cpu: "2", ephemeral-storage: "5Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    storage_line.add_argument(ap)
    line = storage_line.check(ap.parse_args(argv).storage_line)
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    if "origin/main" not in subprocess.run(["git", "branch", "-r", "--contains", commit], cwd=ROOT, capture_output=True, text=True).stdout:
        raise SystemExit(f"FATAL: {commit[:7]} is not pushed; the pod clones it from GitHub")
    out = OUT_DIR / f"job-render-gallery-{commit[:7]}-raunav.yaml"
    out.write_text(SPEC.format(short=commit[:7], commit=commit, image=IMAGE, line=line))
    print(out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
