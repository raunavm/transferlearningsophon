#!/usr/bin/env python3
"""The GPU job of the UMAP figures (PI 2026-11-05): the class token of the 188- and 17-class models on
one JetClass test file per class, frozen and after fine-tuning on 1e6 JetClass jets (the fine-tuned
cells under --ft-root), with experiments/EVAL/extract_features.py on the same files with one loader
worker, then experiments/EVAL/umap_class_token.py on those and on the stored JetClass-II, top and
quark/gluon features, into /data/results/eval/<out-name>/. umap-learn is pinned here (the image has
none).

    python3 scripts/build_umap_jobs.py --tag mtx-s2.63 --ft-root /data/results/ft_v2/best70 --out-name umap_preview
    python3 scripts/build_umap_jobs.py --tag mtx-s2.NN --ft-root /data/results/ft_v2/budget_long --out-name umap_v1
"""
import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "experiments" / "EVAL" / "k8s" / "v2" / "umap"
UMAP_PIN = "umap-learn==0.5.7"
MODELS = (("l188-s1", 188), ("r16q1-s1", 17))
CFG = "configs/finetune/JetClassI_sophon_noweight.yaml"
LP_OLD = "/data/results/eval/v2_linprobe"
STRIDE = 10         # every tenth jet of the ten files: 10,000 per class, of which the figure draws 1,000


def _load(name: str, rel: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / rel)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def spec(tag: str, ft_root: str, out_name: str) -> str:
    launch = _load("build_mtx_launch", "scripts/build_mtx_launch.py")
    classes = " ".join(_load("build_ft_budget_jobs", "scripts/build_ft_budget_jobs.py").JC1_CLASSES)
    out = f"/data/results/eval/{out_name}"
    per_model = "\n".join(f"""CK=$(python3 -c "import json; print(json.load(open('{LP_OLD}/mtx-{m}/jc1/test/best70/manifest.json'))['checkpoint'])")
CELL={ft_root}/leg2/{m}/N1000000/s1
[ -f ${{CELL}}/DONE ] && [ -f ${{CELL}}/net_best_epoch_state.pt ] || {{ echo "FATAL: ${{CELL}} is not done"; exit 42; }}
x frozen mtx-{m} ${{CK}} {k}
x ft mtx-{m} ${{CELL}}/net_best_epoch_state.pt 10""" for m, k in MODELS)
    script = f"""set -euo pipefail
retry () {{ for T in 1 2 3 4 5; do "$@" && return 0; echo "attempt $T failed: $1"; sleep 30; done; return 1; }}
clone () {{ mkdir -p /workspace && cd /workspace && rm -rf tls && git clone -q --depth 1 --branch {tag} https://github.com/raunavm/transferlearningsophon.git tls; }}
retry clone || exit 1
cd /workspace/tls
git rev-parse HEAD
retry pip install --no-cache-dir -q {UMAP_PIN} || exit 1
python3 experiments/FT/gpu_probe.py || {{ sleep 120; exit 43; }}
[ ! -f {out}/DONE ] || {{ echo "{out} done"; exit 0; }}
USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
[ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data at ${{USED}}%"; exit 42; }}
FILES=""; for C in {classes}; do FILES="${{FILES}} $(ls /data/JetClass/Pythia/test_20M/${{C}}_*.root | sort | head -1)"; done
[ "$(echo ${{FILES}} | wc -w)" -eq 10 ] || {{ echo "FATAL: JetClass test files"; exit 42; }}
# x KIND MODEL CHECKPOINT K: the class token on FILES, every {STRIDE}th jet, one loader worker
x () {{
  D={out}/jc1/$2/$1
  [ -f ${{D}}/manifest.json ] && return 0
  python3 experiments/EVAL/extract_features.py --checkpoint $3 --num-classes $4 --arm UMAP_$2_$1 \\
    --data-config {CFG} --data-test ${{FILES}} --observers jet_pt --stride {STRIDE} --num-workers 1 --out ${{D}}
}}
{per_model}
python3 experiments/EVAL/umap_class_token.py --jc1-dir {out}/jc1 --out-dir {out}
touch {out}/DONE
echo "UMAP COMPLETE"
"""
    body = "\n".join(("          " + ln) if ln else "" for ln in script.splitlines())
    exclude = ", ".join(f'"{n}"' for n in launch.V2_BAD_NODES + launch.V2_LATER_BAD_NODES)
    return f"""apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_umap_jobs.py -- the UMAP figures (PI 2026-11-05). Writes new files only.
  name: {out_name.replace("_", "-")}-raunav
  namespace: cms-ml
spec:
  backoffLimit: 1
  activeDeadlineSeconds: 21600
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {launch.V2_IMAGE}
        command: ["/bin/bash", "-c"]
        args:
        - |
{body}
        resources:
          requests: {{ memory: "32Gi", cpu: "4", nvidia.com/gpu: "1", ephemeral-storage: "20Gi" }}
          limits:   {{ memory: "32Gi", cpu: "4", nvidia.com/gpu: "1", ephemeral-storage: "20Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
        - {{ name: dshm, mountPath: /dev/shm }}
      tolerations:
      - {{ key: "nvidia.com/gpu", operator: "Exists", effect: "PreferNoSchedule" }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
              - key: kubernetes.io/hostname
                operator: NotIn
                values: [{exclude}]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
      - name: dshm
        emptyDir: {{ medium: Memory, sizeLimit: "8Gi" }}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tag", required=True)
    ap.add_argument("--ft-root", required=True, help="the fine-tuning root whose leg2/<init>/N1000000/s1 cells to read")
    ap.add_argument("--out-name", required=True, help="the folder under /data/results/eval/")
    a = ap.parse_args(argv)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    p = OUT_DIR / f"job-{a.out_name.replace('_', '-')}-raunav.yaml"
    p.write_text(spec(a.tag, a.ft_root, a.out_name))
    print(p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
