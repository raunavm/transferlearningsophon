#!/usr/bin/env python3
"""The CPU job for the figures added 2026-11-05: ROC curves of the linear probes on top and quark/gluon
(F6-app, under the substitutions chosen on validation), one-vs-rest curves of JetClass-II fine-tuning
(A3R-ft), and the t-SNE of the class token.

    python3 scripts/build_gallery_data_job.py --tag mtx-s2.61
    python3 scripts/build_gallery_data_job.py --tag mtx-s2.NN --mode sib2   # every X->ee / X->mumu test jet
    python3 scripts/build_gallery_data_job.py --tag mtx-s2.NN --mode long   # the long-budget JetClass-II cells
    python3 scripts/build_gallery_data_job.py --tag mtx-s2.NN --mode long-jc1   # the long-budget JetClass cells
"""
import argparse
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMAGE = "gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning:cu121"
OUT = ROOT / "experiments" / "FT" / "k8s" / "curves" / "job-gallery-data-raunav.yaml"
ROC = "/data/results/ft_v2/curves_v2"
PROBS = "/data/results/eval/v2_linprobe_bal/fits_v4_fill_probs"
JC2_TREE, JC2_N = "/data/results/ft_v2/budget/leg_jc2b", 1_000_000


def paper_models() -> list:
    return [l.strip() for l in (ROOT / "configs/arms/v2_paper_runs.txt").read_text().splitlines()
            if l.strip() and not l.startswith("#")]


def calls() -> str:
    models = " ".join(paper_models())
    label_sets = " ".join(m.removeprefix("mtx-") for m in paper_models() if m.split("-")[1] in ("l188", "l162", "r42q1", "r16q1"))
    out = [f"python3 experiments/FT/roc_points.py probes --family top_probe --probs-root {PROBS} --ckpt best70.itop4 "
           f"--files top_N1200000 --models {models} --out-dir {ROC}/top_probe",
           f"echo done > {ROC}/top_probe/DONE",
           f"python3 experiments/FT/roc_points.py probes --family qg_probe --probs-root {PROBS} --ckpt best70.nqg "
           f"--files qg_N1600000 qg_herwig_N1600000 --models {models} --out-dir {ROC}/qg_probe",
           f"echo done > {ROC}/qg_probe/DONE",
           f"python3 experiments/FT/roc_points.py ft --family jc2_ft_ovr --tree {JC2_TREE} --task jc2b --n {JC2_N} "
           f"--inits {label_sets} scratch --out-dir {ROC}/jc2_ft_ovr",
           f"echo done > {ROC}/jc2_ft_ovr/DONE",
           "python3 experiments/EVAL/tsne_class_token.py --out-dir /data/results/eval/tsne_v1"]
    return "\n".join("          " + c for c in out)


SPEC = """apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_gallery_data_job.py. CPU only; writes new files only.
  name: gallery-data-raunav
  namespace: cms-ml
spec:
  backoffLimit: 1
  activeDeadlineSeconds: 28800
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {image}
        command: ["/bin/bash", "-c"]
        args:
        - |
          set -euo pipefail
          for T in 1 2 3 4 5; do git clone -q --depth 1 --branch "{tag}" https://github.com/raunavm/transferlearningsophon.git /workspace/repo && break; sleep 30; done
          cd /workspace/repo
          USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
          [ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data is ${{USED}}% full"; exit 42; }}
          pip install --no-cache-dir -q pyarrow==25.0.1 scikit-learn
          export OMP_NUM_THREADS=8 OPENBLAS_NUM_THREADS=8 MKL_NUM_THREADS=8
          mkdir -p {roc}/top_probe {roc}/qg_probe {roc}/jc2_ft_ovr
{calls}
          echo "GALLERY DATA COMPLETE"
        resources:
          requests: {{ memory: "32Gi", cpu: "8", ephemeral-storage: "5Gi" }}
          limits:   {{ memory: "32Gi", cpu: "8", ephemeral-storage: "5Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
"""


SIB2 = "/data/results/eval/v2_linprobe_bal/fits_v4_sib2"      # build_jc2bal_jobs.sibx_spec
LONG_JC2_TREE = "/data/results/ft_v2/budget_long/leg_jc2b"
LONG_JC1_TREE = "/data/results/ft_v2/budget_long/leg2"
LONG_JC1_FULL = "/data/results/ft_v2/curves/full_budget_long_leg2.json"   # beside ft_curves.py's full_best70_leg2.json


def calls_sib2() -> str:
    """X->ee vs X->mumu on every test jet of the pair (PI 2026-11-05), every model, into curves_v2/pairs_sib2."""
    models = " ".join(paper_models() + [f"init-s{k}" for k in (1, 2, 3)])
    out = [f"python3 experiments/FT/roc_points.py probes --family pairs --probs-root {SIB2}_probs --fits-root {SIB2} "
           f"--files jc2bal_pairs_ee_vs_mm --models {models} --out-dir {ROC}/pairs_sib2",
           f"echo done > {ROC}/pairs_sib2/DONE"]
    return "\n".join("          " + c for c in out)


def calls_long() -> str:
    """One-vs-rest curves of the long-budget JetClass-II cells at 1e6 (the reruns at the limit, from scratch and
    the eight partitions) into curves_v2/jc2_ft_ovr_long; the figures let them replace jc2_ft_ovr's."""
    inits = " ".join(sorted(d.split("/")[-1] for d in _long_inits()))
    out = [f"python3 experiments/FT/roc_points.py ft --family jc2_ft_ovr --tree {LONG_JC2_TREE} --task jc2b --n {JC2_N} "
           f"--inits {inits} --out-dir {ROC}/jc2_ft_ovr_long",
           f"echo done > {ROC}/jc2_ft_ovr_long/DONE"]
    return "\n".join("          " + c for c in out)


def calls_long_jc1() -> str:
    """The long-budget JetClass cells at 1e6 (every paper run and three seeds from scratch, one tree): ROC curves
    into curves_v2/jc1_ft_long and jc1_ft_ovr_long, ParT's per-class table into curves/full_budget_long_leg2.json;
    the readers let them replace the old cells' once they hold every model. Every cell must be DONE first, since
    ft_curves.py writes its file once."""
    bfb = _bfb()
    cells, n = bfb.long_cells("jc1", "1e-3", "1e-3"), bfb.LONG_N
    inits = " ".join(sorted({c["init"] or "scratch" for c in cells}))
    out = ["for c in " + " ".join(c["out"] for c in cells)
           + '; do [ -e "${c}/DONE" ] || { echo "FATAL: ${c} not DONE"; exit 42; }; done']
    for fam in ("jc1_ft", "jc1_ft_ovr"):
        out += [f"python3 experiments/FT/roc_points.py ft --family {fam} --tree {LONG_JC1_TREE} --task jc1 --n {n} "
                f"--inits {inits} --out-dir {ROC}/{fam}_long",
                f"echo done > {ROC}/{fam}_long/DONE"]
    out.append(f"[ -e {LONG_JC1_FULL} ] || python3 experiments/FT/ft_curves.py cells --tree {LONG_JC1_TREE} --task jc1 "
               f"--n {n} --out {LONG_JC1_FULL}")
    return "\n".join("          " + c for c in out)


def _bfb():
    import importlib.util
    spec = importlib.util.spec_from_file_location("build_ft_budget_jobs", ROOT / "scripts/build_ft_budget_jobs.py")
    bfb = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bfb)
    return bfb


def _long_inits() -> list:
    bfb = _bfb()
    cells = bfb.long_cells("jc2b", "1e-3", "1e-3") + bfb.long_ctrl_cells("1e-3")
    return sorted({c["init"] or "scratch" for c in cells if "mass" not in c["init"]})


def calls_kin() -> str:
    """The kinematic-only run's top probe curve: its inputs have no absent slots, so its probe is the plain best70
    fit (fits_v4_probs), beside the label sets' imputed-fill probes in top_probe (PI 2026-11-07)."""
    out = [f"python3 experiments/FT/roc_points.py probes --family top_probe --probs-root {PROBS.replace('_fill_probs', '_probs')} "
           f"--ckpt best70 --files top_N1200000 --models mtx-l188kin-s1 --out-dir {ROC}/top_probe"]
    return "\n".join("          " + c for c in out)


MODES = {"": (calls, "gallery-data-raunav", "top_probe qg_probe jc2_ft_ovr"),
         "kin": (calls_kin, "gallery-data-kin-raunav", "top_probe"),
         "sib2": (calls_sib2, "gallery-data-sib2-raunav", "pairs_sib2"),
         "long": (calls_long, "gallery-data-long-raunav", "jc2_ft_ovr_long"),
         "long-jc1": (calls_long_jc1, "gallery-data-long-jc1-raunav", "jc1_ft_long jc1_ft_ovr_long")}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--mode", default="", choices=tuple(MODES))
    a = ap.parse_args()
    fn, name, dirs = MODES[a.mode]
    out = OUT.with_name(f"job-{name}.yaml")
    out.parent.mkdir(parents=True, exist_ok=True)
    text = SPEC.format(image=IMAGE, tag=a.tag, roc=ROC, calls=fn())
    text = text.replace("name: gallery-data-raunav", f"name: {name}").replace(
        f"mkdir -p {ROC}/top_probe {ROC}/qg_probe {ROC}/jc2_ft_ovr", "mkdir -p " + " ".join(f"{ROC}/{d}" for d in dirs.split()))
    out.write_text(text)
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
