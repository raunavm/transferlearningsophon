SIB2 = "/data/results/eval/v2_linprobe_bal/fits_v4_sib2"      # build_jc2bal_jobs.sibx_spec
LONG_JC2_TREE = "/data/results/ft_v2/budget_long/leg_jc2b"
LONG_JC1_TREE = "/data/results/ft_v2/budget_long/leg2"
LONG_JC1_FULL = "/data/results/ft_v2/curves/full_budget_long_leg2.json"   # beside ft_curves.py's full_best70_leg2.json


def calls_sib2() -> str:
    """X->ee vs X->mumu on every test jet of the pair (PI 2026-11-05), every model, into curves_v2/pairs_sib2."""
    models = " ".join(paper_models() + [f"init-s{k}" for k in (1, 2, 3)])
    out = [f"python3 experiments/FT/roc_points.py probes --family pairs --probs-root {SIB2}_probs --fits-root {SIB2} "
           f"--files jc2bal_pairs_ee_vs_mm --models {models} --out-dir {ROC}/pairs_sib2",
           f"echo done > {ROC}/pairs_sib2/DONE"]
    return "\n".join("          " + c for c in out)


def calls_long() -> str:
    """One-vs-rest curves of the long-budget JetClass-II cells at 1e6 (the reruns at the limit, from scratch and
    the eight partitions) into curves_v2/jc2_ft_ovr_long; the figures let them replace jc2_ft_ovr's."""
    inits = " ".join(sorted(d.split("/")[-1] for d in _long_inits()))
    out = [f"python3 experiments/FT/roc_points.py ft --family jc2_ft_ovr --tree {LONG_JC2_TREE} --task jc2b --n {JC2_N} "
           f"--inits {inits} --out-dir {ROC}/jc2_ft_ovr_long",
           f"echo done > {ROC}/jc2_ft_ovr_long/DONE"]
    return "\n".join("          " + c for c in out)


def calls_long_jc1() -> str:
    """The long-budget JetClass cells at 1e6 (every paper run and three seeds from scratch, one tree): ROC curves
    into curves_v2/jc1_ft_long and jc1_ft_ovr_long, ParT's per-class table into curves/full_budget_long_leg2.json;
    the readers let them replace the old cells' once they hold every model. Every cell must be DONE first, since
    ft_curves.py writes its file once."""
    bfb = _bfb()
    cells, n = bfb.long_cells("jc1", "1e-3", "1e-3"), bfb.LONG_N
    inits = " ".join(sorted({c["init"] or "scratch" for c in cells}))
    out = ["for c in " + " ".join(c["out"] for c in cells)
           + '; do [ -e "${c}/DONE" ] || { echo "FATAL: ${c} not DONE"; exit 42; }; done']
    for fam in ("jc1_ft", "jc1_ft_ovr"):
        out += [f"python3 experiments/FT/roc_points.py ft --family {fam} --tree {LONG_JC1_TREE} --task jc1 --n {n} "
                f"--inits {inits} --out-dir {ROC}/{fam}_long",
                f"echo done > {ROC}/{fam}_long/DONE"]
    out.append(f"[ -e {LONG_JC1_FULL} ] || python3 experiments/FT/ft_curves.py cells --tree {LONG_JC1_TREE} --task jc1 "
               f"--n {n} --out {LONG_JC1_FULL}")
    return "\n".join("          " + c for c in out)


FULL_JC1_TREE, FULL_JC2_TREE = "/data/results/ft_v2/budget_long_fulldecay/leg2", "/data/results/ft_v2/budget_long_fulldecay/leg_jc2b"
FULL_JC1 = "/data/results/ft_v2/curves/full_budget_long_fulldecay_leg2.json"


def calls_scratch_full() -> str:
    """The from-scratch cells at 1e6 with their whole flat+decay schedule (build_ft_budget_jobs.long_scratch_full_cells,
    PI 2026-11-07), every one DONE first: the families the old from-scratch cells fed (jc2_ft_ovr, jc1_ft, jc1_ft_ovr)
    into <family>_fulldecay and ParT's per-class table into a new file; the readers (mlst_v4.load_family,
    figstyle/gallery_common, mlst_results.jc1_full) let them replace the old from-scratch seeds."""
    bfb = _bfb()
    cells, n = bfb.long_scratch_full_cells("jc2b", "1e-3") + bfb.long_scratch_full_cells("jc1", "1e-3"), bfb.LONG_N
    out = ["for c in " + " ".join(c["out"] for c in cells)
           + '; do [ -e "${c}/DONE" ] || { echo "FATAL: ${c} not DONE"; exit 42; }; done']
    for fam, tree, task in (("jc2_ft_ovr", FULL_JC2_TREE, "jc2b"), ("jc1_ft", FULL_JC1_TREE, "jc1"),
                            ("jc1_ft_ovr", FULL_JC1_TREE, "jc1")):
        out += [f"python3 experiments/FT/roc_points.py ft --family {fam} --tree {tree} --task {task} --n {n} "
                f"--inits scratch --out-dir {ROC}/{fam}_fulldecay",
                f"echo done > {ROC}/{fam}_fulldecay/DONE"]
    out.append(f"[ -e {FULL_JC1} ] || python3 experiments/FT/ft_curves.py cells --tree {FULL_JC1_TREE} --task jc1 "
               f"--n {n} --out {FULL_JC1}")
    return "\n".join("          " + c for c in out)


def _bfb():
    import importlib.util
    spec = importlib.util.spec_from_file_location("build_ft_budget_jobs", ROOT / "scripts/build_ft_budget_jobs.py")
    bfb = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bfb)
    return bfb


def _long_inits() -> list:
    bfb = _bfb()
    cells = bfb.long_cells("jc2b", "1e-3", "1e-3") + bfb.long_ctrl_cells("1e-3")
    return sorted({c["init"] or "scratch" for c in cells if "mass" not in c["init"]})


def calls_kin() -> str:
    """The kinematic-only run's top probe curve: its inputs have no absent slots, so its probe is the plain best70
    fit (fits_v4_probs), beside the label sets' imputed-fill probes in top_probe (PI 2026-11-07)."""
    out = [f"python3 experiments/FT/roc_points.py probes --family top_probe --probs-root {PROBS.replace('_fill_probs', '_probs')} "
           f"--ckpt best70 --files top_N1200000 --models mtx-l188kin-s1 --out-dir {ROC}/top_probe"]
    return "\n".join("          " + c for c in out)


SCULPT_FT = "/data/results/eval/v2_head/sculpting_ft"


def _hb():
    spec = importlib.util.spec_from_file_location("build_head_jobs", ROOT / "scripts/build_head_jobs.py")
    hb = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(hb)
    return hb


def ft_trees() -> dict:
    """{tree: [init]} of build_head_jobs.ft_head_cells (<tree>/<init>/N1000000/s<S>), in its order."""
    out = {}
    for _m, cell in _hb().ft_head_cells():
        tree, init, _n, _s = cell.rsplit("/", 3)
        if init not in out.setdefault(tree, []):
            out[tree].append(init)
    return out


def calls_ft_pairs_sculpt() -> str:
    """The JetClass-II fine-tuning at 1e6 (plan 2026-11-08 step 2), from each cell's outputs on the TEST2M jets of
    the head sculpting (build_head_jobs.py --ft-head; every model's manifest present first): the seven pairs of
    the pair table into curves_v2/pairs_ft, the 27 paper runs and the three full-schedule from-scratch seeds in the
    one directory, DONE after all of them; then the QCD mass sculpting of each into SCULPT_FT, DONE after the last
    sculpting_ft.py call (one per tree), so the pull (pull_mlst_data.py) never takes a part of it."""
    hb = _hb()
    trees = ft_trees()
    heads = " ".join(f"{hb.FT_HEAD_ROOT}/{m}/manifest.json" for m, _c in hb.ft_head_cells())
    out = [f"for f in {heads}" + '; do [ -e "${f}" ] || { echo "FATAL: no ${f}"; exit 42; }; done']
    out += [f"python3 experiments/FT/roc_points.py ft --family pairs_ft --tree {tree} --task jc2b --n {JC2_N} "
            f"--inits {' '.join(inits)} --head-root {hb.FT_HEAD_ROOT} --out-dir {ROC}/pairs_ft"
            for tree, inits in trees.items()]
    out.append(f"echo done > {ROC}/pairs_ft/DONE")
    out += [f"python3 experiments/EVAL/sculpting_ft.py --tree {tree} --n {JC2_N} --inits {' '.join(inits)} "
            f"--head-root {hb.FT_HEAD_ROOT} --out-dir {SCULPT_FT}" for tree, inits in trees.items()]
    out.append(f"echo done > {SCULPT_FT}/DONE")
    return "\n".join("          " + c for c in out)


SCULPT_BOOT = "/data/results/eval/v2_head/sculpting_boot.json"


def calls_sculpt_boot() -> str:
    """sculpting_boot.py on the head outputs of the 22 runs of the sculpting rerun (build_head_jobs.SCULPT_V3), its
    replica 0 checked against their sculpting_v3 documents, every one present first."""
    hb = _hb()
    heads = [f"{hb.HEAD_ROOT}/{m}/test/best70/head_outputs.npz" for m in hb.SCULPT_V3]
    heads += [f"{hb.SCULPT_V3_DIR}/{m}_sculpting.json" for m in hb.SCULPT_V3]
    sets = " ".join(f"{m}={arm}" for m, _r, arm, _k, _g in hb.flav_models())
    out = ["for f in " + " ".join(heads) + '; do [ -e "${f}" ] || { echo "FATAL: no ${f}"; exit 42; }; done',
           f"python3 experiments/EVAL/sculpting_boot.py --head-root {hb.HEAD_ROOT} --models {' '.join(hb.SCULPT_V3)} "
           f"--label-set {sets} --replicas 200 --sculpting-dir {hb.SCULPT_V3_DIR} --out {SCULPT_BOOT}"]
    return "\n".join("          " + c for c in out)


JC1_BOOT = "/data/results/ft_v2/jc1_acc_boot"
JC1_BOOT_N = 1_000_000


def calls_jc1_acc_boot() -> str:
    """jc1_acc_boot.py on the long-budget JetClass cells at 1e6 (PI 2026-11-09), replica 0 checked against their
    read-out; DONE after it, so the pull never takes a part."""
    root = "/data/results/ft_v2/budget_long"
