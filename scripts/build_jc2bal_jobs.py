def _probe_builder():
    spec = importlib.util.spec_from_file_location("build_linprobe_jobs", ROOT / "scripts" / "build_linprobe_jobs.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
