#!/usr/bin/env python3
"""ParT's from-scratch top-tagging run on our cluster, and the bisect toward our recipe (plan 2.4).

Our from-scratch top tagging reaches Rej30% 1,412 +- 20 (three seeds) against ParT's 1,602 +- 81
(ParT Table 5), while our quark/gluon run matches ParT. Our budget and optimizer equal ParT's
released script (train_TopLandscape.sh: batch 512, 2400 x 512 jets per epoch, 20 epochs, lr 1e-3,
weight decay 0.01, AMP, Ranger, weaver's default flat+decay). What differs is the network (Sophon's
512-unit head), Sophon's rescaling of every particle four-momentum by 500 GeV / jet pT, the 17
inputs with 10 set to zero, and our staging of the top data. Each variant here changes one thing,
on ParT's own data (TopLandscape.tar of ParT's get_datasets.py, md5-checked):

  part      ParT's script unchanged (--tensorboard dropped: it writes logs, not results)
  rescale   ParT's config with Sophon's rescaling (experiments/FT/partrepro/top_kin_rescale.yaml)
  head      ParT's network with Sophon's head, -o fc_params '[(512,0.1)]'

One V100 each, ~3 GPU-h. Output /data/results/partrepro/<variant>/{train.log, pred.root,
metrics.json}; metrics from experiments/FT/partrepro_metrics.py.

    python3 scripts/build_partrepro_jobs.py --tag mtx-s2.22 part rescale head
"""
import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "experiments" / "FT" / "k8s" / "partrepro"
PART_REPO = "https://github.com/jet-universe/particle_transformer.git"
PART_COMMIT = "2925bdb"
DATA_URL = "https://hqu.web.cern.ch/datasets/TopLandscape/TopLandscape.tar"
DATA_MD5 = "4fca2e47afbf321b0f201da6b804c404"
GPU = "Tesla-V100-SXM2-32GB"
PART_CFG = "data/TopLandscape/top_kin.yaml"
VARIANTS = {
    "part": {"config": PART_CFG, "extra": ""},
    "rescale": {"config": "/workspace/tls/experiments/FT/partrepro/top_kin_rescale.yaml", "extra": ""},
    "head": {"config": PART_CFG, "extra": "-o fc_params '[(512,0.1)]'"},
}


def _launch():
    spec = importlib.util.spec_from_file_location("build_mtx_launch", ROOT / "scripts" / "build_mtx_launch.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def spec(variant: str, tag: str) -> tuple:
    v = VARIANTS[variant]
    launch = _launch()
    name = f"partrepro-{variant}-raunav"
    exclude = ", ".join(f'"{n}"' for n in launch.V2_BAD_NODES)
    script = f"""set -euo pipefail
OUT=/data/results/partrepro/{variant}
USED=$(df --output=pcent /data | tail -1 | tr -dc 0-9)
[ "${{USED}}" -le 85 ] || {{ echo "FATAL: /data at ${{USED}}%"; exit 42; }}
[ ! -f ${{OUT}}/metrics.json ] || {{ echo "${{OUT}} is done"; cat ${{OUT}}/metrics.json; exit 0; }}
mkdir -p ${{OUT}}
git clone -q --depth 1 --branch {tag} https://github.com/raunavm/transferlearningsophon.git /workspace/tls
git clone -q {PART_REPO} /workspace/part && cd /workspace/part && git checkout -q {PART_COMMIT}
git rev-parse HEAD | tee ${{OUT}}/part_commit.txt
pip install --no-cache-dir -q pyarrow==25.0.1 || exit 1
mkdir -p /workspace/data && cd /workspace/data
python3 -c "import urllib.request,sys; urllib.request.urlretrieve(sys.argv[1], 'TopLandscape.tar')" {DATA_URL}
echo "{DATA_MD5}  TopLandscape.tar" | md5sum -c - || {{ echo "FATAL: TopLandscape.tar md5"; exit 42; }}
tar -xf TopLandscape.tar && rm TopLandscape.tar && find /workspace/data -name "*.parquet" | tee ${{OUT}}/files.txt
D=$(dirname $(find /workspace/data -name train_file.parquet | head -1))
cd /workspace/part
nvidia-smi -L | tee ${{OUT}}/gpu.txt
weaver --data-train ${{D}}/train_file.parquet --data-val ${{D}}/val_file.parquet --data-test ${{D}}/test_file.parquet \\
  --data-config {v['config']} --network-config networks/example_ParticleTransformer.py \\
  --use-amp --optimizer-option weight_decay 0.01 {v['extra']} \\
  --model-prefix ${{OUT}}/net --num-workers 1 --fetch-step 1 --in-memory \\
  --batch-size 512 --samples-per-epoch $((2400 * 512)) --samples-per-epoch-val $((800 * 512)) --num-epochs 20 --gpus 0 \\
  --start-lr 1e-3 --optimizer ranger --log ${{OUT}}/train.log --predict-output ${{OUT}}/pred.root 2>&1 | tee ${{OUT}}/stdout.log
python3 /workspace/tls/experiments/FT/partrepro_metrics.py ${{OUT}}/pred.root --out ${{OUT}}/metrics.json
echo "PARTREPRO COMPLETE"
"""
    body = "\n".join(("          " + ln) if ln else "" for ln in script.splitlines())
    return name, f"""apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_partrepro_jobs.py -- ParT top tagging from scratch, variant {variant}.
  name: {name}
  namespace: cms-ml
spec:
  backoffLimit: 1
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {launch.V2_IMAGE}
        command: ["/bin/bash", "-c"]
        args:
        - |
{body}
        resources:
          requests: {{ memory: "48Gi", cpu: "6", nvidia.com/gpu: "1", ephemeral-storage: "20Gi" }}
          limits:   {{ memory: "48Gi", cpu: "6", nvidia.com/gpu: "1", ephemeral-storage: "20Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
        - {{ name: dshm, mountPath: /dev/shm }}
      tolerations:
      - {{ key: "nvidia.com/gpu", operator: "Exists", effect: "PreferNoSchedule" }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
              - key: nvidia.com/gpu.product
                operator: In
                values: ["{GPU}"]
              - key: kubernetes.io/hostname
                operator: NotIn
                values: [{exclude}]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
      - name: dshm
        emptyDir: {{ medium: Memory, sizeLimit: "8Gi" }}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("variants", nargs="+", choices=sorted(VARIANTS))
    a = ap.parse_args(argv)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for v in a.variants:
        name, text = spec(v, a.tag)
        p = OUT_DIR / f"job-{name}.yaml"
        p.write_text(text)
        print(p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
