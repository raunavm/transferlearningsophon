#!/usr/bin/env python3
"""Kinematic-only pretraining arms (PI, 2026-10-30): the 188- and 17-class label sets with
the seven kinematic particle features only.

ParT pretrained a separate model on the kinematic features alone for top tagging, whose
data provide only four-momenta (ParT Sec. 5.2, Table 2). Our models see all 17 features in
pretraining and receive the missing ten as zeros on the top data. These two arms are the
in-distribution test of the label set on top tagging, and the entries comparable with
ParT-f.t. in the benchmark table.

Each arm is its parent config (configs/arms/L188.yaml, configs/arms/R16_Q1.yaml) with ten
lines of `inputs.pf_features` removed -- charge, the five particle-type flags and the four
track-displacement variables -- and its header comment rewritten. Nothing else changes: the
`weights:` block is copied byte for byte (I2), and the selection, labels and the other input
groups are the parent's. pf_points and pf_vectors (the pairwise features) are kinematic and
unchanged. The seven features kept are the parent's own kinematic features, in its order and
with its scaling (Sophon's jet-pT rescaling included), so a kinematic run differs from the
full-feature run of the same label set only by the ten inputs.

Writes configs/arms/v2/L188_KIN.yaml, configs/arms/v2/R16_Q1_KIN.yaml and the registry
configs/arms/v2_kin.json (outside configs/arms/v2_grid.json, which the probe, extraction and
fine-tuning builders read for the 37-run grid). --check verifies the files on disk.
"""
import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
ARMS = REPO / "configs" / "arms"
V2 = ARMS / "v2"
REGISTRY = ARMS / "v2_kin.json"

PARENTS = {"L188_KIN": ("L188", 188), "R16_Q1_KIN": ("R16_Q1", 17)}
DROP = ("         - [part_charge, null]\n",
        "         - [part_isChargedHadron, null]\n",
        "         - [part_isNeutralHadron, null]\n",
        "         - [part_isPhoton, null]\n",
        "         - [part_isElectron, null]\n",
        "         - [part_isMuon, null]\n",
        "         - [part_d0, null]\n",
        "         - [part_d0err, 0, 1, 0, 1]\n",
        "         - [part_dz, null]\n",
        "         - [part_dzerr, 0, 1, 0, 1]\n")
KEPT = ("part_pt_scale_log", "part_e_scale_log", "part_logptrel", "part_logerel",
        "part_deltaR", "part_deta", "part_dphi")


def parent_header(parent: str) -> str:
    return (f"# configs/arms/{parent}.yaml\n"
            "# GENERATED by scripts/build_arm_configs.py -- do not hand-edit.\n"
            "#\n"
            "# Differs from configs/data/JetClassII_base.yaml in the `labels:` block\n"
            "# and NOTHING ELSE. The `weights:` block is copied byte for byte, which\n"
            "# is what makes the training stream bit-identical across arms (I2).\n"
            "# NEVER edit the weights: block. Regenerate this file instead.\n")


def header(arm: str, parent: str) -> str:
    return (f"# configs/arms/v2/{arm}.yaml\n"
            f"# GENERATED by scripts/build_kin_arms.py from configs/arms/{parent}.yaml"
            " -- do not hand-edit.\n"
            "#\n"
            f"# Differs from configs/arms/{parent}.yaml in `inputs.pf_features` and NOTHING\n"
            "# ELSE: the seven kinematic features only (no charge, particle-type flags or track\n"
            "# displacement). The `weights:` block is copied byte for byte (I2).\n"
            "# NEVER edit the weights: block. Regenerate this file instead.\n")


def block(text: str, name: str) -> str:
    """The top-level block `name:` of a config, up to the next top-level key."""
    lines = text.splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l.startswith(f"{name}:"))
    end = next((i for i in range(start + 1, len(lines))
                if lines[i][:1].isalpha() and ":" in lines[i]), len(lines))
    return "".join(lines[start:end])


def pf_feature_names(text: str) -> list:
    feats = block(text, "inputs").split("pf_features:", 1)[1].split("pf_vectors:", 1)[0]
    return [l.strip()[2:].strip("[]").split(",")[0].strip()
            for l in feats.splitlines() if l.strip().startswith("- ")]


def build_one(arm: str) -> str:
    parent, _ = PARENTS[arm]
    text = (ARMS / f"{parent}.yaml").read_text()
    head = parent_header(parent)
    if not text.startswith(head):
        raise SystemExit(f"FATAL: configs/arms/{parent}.yaml does not start with its generated header")
    text = header(arm, parent) + text[len(head):]
    for line in DROP:
        if text.count(line) != 1:
            raise SystemExit(f"FATAL: {parent}: expected one {line.strip()!r}")
        text = text.replace(line, "")
    return text


def check(arm: str, text: str) -> list:
    parent, _ = PARENTS[arm]
    ptext = (ARMS / f"{parent}.yaml").read_text()
    bad = []
    if pf_feature_names(text) != list(KEPT):
        bad.append(f"{arm}: pf_features {pf_feature_names(text)}")
    for name in ("selection", "new_variables", "preprocess", "labels", "observers", "weights"):
        if block(text, name) != block(ptext, name):
            bad.append(f"{arm}: block {name} differs from {parent}")
    for grp in ("pf_points:", "pf_vectors:", "pf_mask:"):
        a = block(text, "inputs").split(grp, 1)[1]
        b = block(ptext, "inputs").split(grp, 1)[1]
        if a.split("\n   pf_", 1)[0] != b.split("\n   pf_", 1)[0]:
            bad.append(f"{arm}: input group {grp} differs from {parent}")
    return bad


def registry() -> dict:
    arms = [{"name": arm, "config": f"configs/arms/v2/{arm}.yaml", "parent": parent,
             "num_classes": k, "mass_lambda": None, "runs": 1, "extra_selection": None,
             "objective": "classification", "features": list(KEPT)}
            for arm, (parent, k) in PARENTS.items()]
    return {"generated_by": "scripts/build_kin_arms.py",
            "what": "kinematic-only pretraining arms (PI, 2026-10-30): seed 1 of the 188- and "
                    "17-class label sets with the seven kinematic particle features",
            "arms": arms}


def outputs() -> dict:
    out = {V2 / f"{arm}.yaml": build_one(arm) for arm in PARENTS}
    out[REGISTRY] = json.dumps(registry(), indent=1) + "\n"
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify the files on disk, write nothing")
    a = ap.parse_args(argv)
    out = outputs()
    bad = [m for arm in PARENTS for m in check(arm, out[V2 / f"{arm}.yaml"])]
    if a.check:
        bad += [f"{p.relative_to(REPO)} is stale" for p, t in out.items()
                if not p.exists() or p.read_text() != t]
    if bad:
        print("\n".join(bad))
        return 1
    if not a.check:
        for p, t in out.items():
            p.write_text(t)
        print("wrote " + ", ".join(str(p.relative_to(REPO)) for p in out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
