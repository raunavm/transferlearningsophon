#!/usr/bin/env python3
"""The load-check of a storage failure's window (guard v7, PI 2026-11-22): every file under /data/results written
between --since and --until loaded in full with its own reader (experiments/EVAL/storage_scan.py --no-records), on the
CPU, at a pushed tag. Writes the spec and prints its path; the guard applies it.

    python3 scripts/build_storage_scan_job.py --tag mtx-s3.39 --since 2026-11-23T01:00:00Z --until 2026-11-23T02:30:00Z
"""
from __future__ import annotations

import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "experiments" / "EVAL" / "k8s" / "v2" / "storage_window"
IMAGE = ("gitlab-registry.nrp-nautilus.io/escheuller/transfer-learning@"
         "sha256:db235b515a278198ebc6dc2c607c9c38cfb10e6b46e29ed2847ec9f4af6191e7")
STAMP = re.compile(r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$")


def spec(tag: str, since: str, until: str, roots: str = "/data/results") -> tuple[str, str, str]:
    """(job name, output folder, spec text)."""
    if not (STAMP.match(since) and STAMP.match(until)) or since >= until:
        raise SystemExit(f"FATAL: window {since} .. {until}")
    key = since.replace("-", "").replace(":", "")[:13].lower() + "-" + until.replace("-", "").replace(":", "")[9:13]
    name = f"storage-scan-w{key}-raunav"           # storage-scan-w20261123t0100-0230-raunav
    out = f"/data/results/eval/storage_scan_window/{since}_{until}"
    text = f"""apiVersion: batch/v1
kind: Job
metadata:
  # GENERATED by scripts/build_storage_scan_job.py: every file under {roots} written {since} .. {until} (a storage
  # failure's window, guard v7) loaded in full with its own reader. Reads only; CPU.
  name: {name}
  namespace: cms-ml
spec:
  backoffLimit: 1
  template:
    spec:
      restartPolicy: Never
      containers:
      - name: main
        image: {IMAGE}
        command: ["/bin/bash", "-c"]
        args:
        - |
          set -euo pipefail
          retry () {{ for T in 1 2 3 4 5; do "$@" && return 0; echo "attempt $T failed: $1"; sleep 30; done; return 1; }}
          clone () {{ mkdir -p /workspace && cd /workspace && rm -rf tls && git clone -q --depth 1 --branch {tag} https://github.com/raunavm/transferlearningsophon.git tls; }}
          retry clone || exit 1
          cd /workspace/tls
          retry pip install --no-cache-dir -q pyarrow==25.0.1 || exit 1
          O={out}
          [ ! -e ${{O}}/report.tsv ] || {{ echo "FATAL: ${{O}}/report.tsv exists"; exit 1; }}
          python3 experiments/EVAL/storage_scan.py --since {since} --until {until} --roots {roots} --no-records --out ${{O}}
          echo "SCAN FAILURES $(($(wc -l < ${{O}}/report.tsv) - 1))"
        resources:
          requests: {{ memory: "8Gi", cpu: "2", ephemeral-storage: "5Gi" }}
          limits:   {{ memory: "8Gi", cpu: "2", ephemeral-storage: "5Gi" }}
        volumeMounts:
        - {{ name: data, mountPath: /data }}
      affinity:
        nodeAffinity:
          requiredDuringSchedulingIgnoredDuringExecution:
            nodeSelectorTerms:
            - matchExpressions:
              - key: topology.kubernetes.io/region
                operator: In
                values: ["us-west"]
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: transfer-learning-vol
"""
    return name, out, text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--since", required=True)
    ap.add_argument("--until", required=True)
    ap.add_argument("--roots", default="/data/results")
    a = ap.parse_args(argv)
    name, _, text = spec(a.tag, a.since, a.until, a.roots)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    p = OUT_DIR / f"job-{name}.yaml"
    p.write_text(text)
    print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
