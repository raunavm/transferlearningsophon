"""One Indexed Job that runs a list of existing single-job specs, PARALLEL at a time.

The Job controller releases the pods, so no release loop runs on the laptop (plan 2026-10-29,
operations). Index i runs the container script of the i-th spec, read from that spec file at
the runner's pinned commit, so the scripts are exactly the reviewed and tested ones; the pod
template (image, resources, GPU, affinity, volumes) is the first spec's, and every listed spec
must have the same one. A script's exit 42 fails its index only; a signal is retried.

    python3 scripts/build_indexed_runner.py --name head-x --parallel 3 \\
        experiments/EVAL/k8s/v2/head/job-head-x-*-raunav.yaml
"""
from __future__ import annotations

import argparse
import copy
import pathlib
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "experiments" / "MTX" / "k8s" / "v2" / "indexed"

DISPATCH = """set -uo pipefail
SPECS=({specs})
SPEC=${{SPECS[$JOB_COMPLETION_INDEX]}}
echo "index $JOB_COMPLETION_INDEX: $SPEC at {commit}"
git clone -q https://github.com/raunavm/transferlearningsophon.git /workspace/runner || exit 1
cd /workspace/runner && git checkout -q {commit} || exit 1
python3 -c "import sys, yaml; d = yaml.safe_load(open(sys.argv[1])); \\
print(d['spec']['template']['spec']['containers'][0]['args'][0])" "$SPEC" > /workspace/script.sh || exit 1
cd /workspace && exec bash /workspace/script.sh
"""


def template_of(d: dict) -> dict:
    """The pod template without its script, to check that the specs share one."""
    t = copy.deepcopy(d["spec"]["template"])
    t["spec"]["containers"][0].pop("args")
    return t


def build(name: str, parallel: int, specs: list[pathlib.Path], commit: str) -> str:
    docs = [yaml.safe_load(p.read_text()) for p in specs]
    for p, d in zip(specs, docs):
        if not d["metadata"]["name"].endswith("-raunav"):
            raise SystemExit(f"FATAL: {p} is not one of ours")
        if template_of(d) != template_of(docs[0]):
            raise SystemExit(f"FATAL: {p} has another pod template than {specs[0]}")
    job = copy.deepcopy(docs[0])
    rel = [str(p.resolve().relative_to(ROOT)) for p in specs]
    job["metadata"] = {"name": f"{name}-raunav", "namespace": "cms-ml"}
    job["spec"].pop("backoffLimit", None)
    job["spec"].update({"completionMode": "Indexed", "completions": len(specs), "parallelism": parallel,
                        "backoffLimitPerIndex": 6, "maxFailedIndexes": len(specs)})
    for rule in job["spec"].get("podFailurePolicy", {}).get("rules", []):
        if rule["action"] == "FailJob":
            rule["action"] = "FailIndex"
    job["spec"]["template"]["spec"]["containers"][0]["args"] = [
        DISPATCH.format(specs=" ".join(rel), commit=commit)]
    head = (f"# GENERATED by scripts/build_indexed_runner.py at {commit[:7]}: {len(specs)} specs, "
            f"{parallel} at a time,\n# index i runs the script of the i-th:\n"
            + "".join(f"#   {i}: {r}\n" for i, r in enumerate(rel)))
    return head + yaml.safe_dump(job, sort_keys=False, width=120)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--name", required=True, help="the Job's name, without -raunav")
    ap.add_argument("--parallel", type=int, required=True)
    ap.add_argument("specs", nargs="+", type=pathlib.Path)
    a = ap.parse_args(argv)
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                            check=True).stdout.strip()
    if "origin/main" not in subprocess.run(["git", "branch", "-r", "--contains", commit], cwd=ROOT,
                                           capture_output=True, text=True).stdout:
        raise SystemExit(f"FATAL: {commit[:7]} is not pushed; the pods read the specs from it")
    for p in a.specs:
        if subprocess.run(["git", "diff", "--quiet", commit, "--", str(p)], cwd=ROOT).returncode:
            raise SystemExit(f"FATAL: {p} differs from its committed version")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"job-{a.name}-raunav.yaml"
    out.write_text(build(a.name, a.parallel, a.specs, commit))
    print(out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
