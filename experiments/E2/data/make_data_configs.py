#!/usr/bin/env python3
"""Generate the five E2 weaver data configs from the official Sophon config.

Each JetClassII_<gran>.yaml is byte-identical to JetClassII_full_base.yaml
except for (a) a one-line generated header and (b) the `truth_label:` line,
which remaps jet_label through the frozen map in ../labels/label_maps.json as
a pure elementwise expression (same idiom as the config's own reweight
classes, so weaver evaluates it identically). Everything that controls the
jet stream — selection, inputs, preprocessing, weights/reweighting — is
untouched: all five granularities train on the SAME sampled jets and differ
only in the integer label (the E2 invariant).

Also verifies, for every generated config, that the expression evaluated on
jet_label = 0..187 reproduces the frozen map, and that all other lines match
the base config.

--inject-hists <master.auto.yaml>: after the one shared `make_weight` pass
(run with the g188 config), clone its weaver-generated auto config — which
embeds the computed reweight_hists — into per-granularity auto configs by
swapping only labels.value.truth_label. weaver 0.4.17 discovers the auto file
as <config>.<md5 of config file bytes>.auto.yaml next to the config and uses
it INSTEAD of the config (weaver/utils/dataset.py:330-338), so each clone is
named with its own config's md5. Untested until make_weight runs.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
BASE = HERE / "JetClassII_full_base.yaml"
MAPS = HERE.parent / "labels" / "label_maps.json"
GRANS = ["g2", "g10sem", "g10rand", "g30", "g188"]
LABEL_LINE = re.compile(r"^(\s+truth_label: ).*$")


def runs(idx):
    """Sorted indices -> [(start, stop_exclusive)] contiguous runs."""
    out, start, prev = [], idx[0], idx[0]
    for i in idx[1:]:
        if i != prev + 1:
            out.append((start, prev + 1))
            start = i
        prev = i
    out.append((start, prev + 1))
    return out


def merge_expr(lut):
    """(188,) int map -> elementwise remap expression on jet_label."""
    terms = []
    for g in range(1, int(lut.max()) + 1):
        parts = []
        for a, b in runs(np.where(lut == g)[0].tolist()):
            if b - a == 1:
                parts.append(f"(jet_label == {a})")
            else:
                parts.append(f"((jet_label >= {a}) & (jet_label < {b}))")
        terms.append(f"{g} * ({' | '.join(parts)})")
    return " + ".join(terms)


def generate():
    base_lines = BASE.read_text().splitlines()
    maps = json.loads(MAPS.read_text())
    n_label_lines = sum(bool(LABEL_LINE.match(ln)) for ln in base_lines)
    assert n_label_lines == 1, "base config must contain exactly one truth_label line"

    for gran in GRANS:
        lut = np.asarray(maps[gran]["map"])
        expr = "jet_label" if gran == "g188" else merge_expr(lut)
        header = (f"# GENERATED by make_data_configs.py — granularity {gran} "
                  f"({maps[gran]['num_classes']} classes). Do not edit; only the "
                  f"truth_label line differs from JetClassII_full_base.yaml.")
        out_lines = [header] + [
            LABEL_LINE.match(ln).group(1) + expr if LABEL_LINE.match(ln) else ln
            for ln in base_lines
        ]
        out = HERE / f"JetClassII_{gran}.yaml"
        out.write_text("\n".join(out_lines) + "\n")

        # verify: expression reproduces the frozen map; all other lines untouched
        cfg = yaml.safe_load(out.read_text())
        got = eval(cfg["labels"]["value"]["truth_label"],
                   {"jet_label": np.arange(188), "np": np})
        got = np.asarray(got) if gran != "g188" else np.arange(188)
        assert np.array_equal(got, lut), f"{gran}: expression != frozen map"
        label_idx = next(i for i, ln in enumerate(base_lines) if LABEL_LINE.match(ln))
        diff = [i for i, (a, b) in enumerate(zip(base_lines, out_lines[1:])) if a != b]
        assert diff in ([], [label_idx]), f"{gran}: unexpected diff at lines {diff}"
        print(f"{out.name}: verified (map OK, only the truth_label line differs)")


def inject_hists(master_auto):
    """Clone the g188 make_weight auto config per granularity (shared hists)."""
    maps = json.loads(MAPS.read_text())
    doc = yaml.safe_load(Path(master_auto).read_text())
    assert doc.get("weights", {}).get("reweight_hists"), \
        "master auto config has no reweight_hists — run make_weight first"
    for gran in GRANS:
        lut = np.asarray(maps[gran]["map"])
        doc["labels"]["value"]["truth_label"] = (
            "jet_label" if gran == "g188" else merge_expr(lut))
        cfg = HERE / f"JetClassII_{gran}.yaml"
        md5 = hashlib.md5(cfg.read_bytes()).hexdigest()
        out = HERE / f"JetClassII_{gran}.{md5}.auto.yaml"
        out.write_text(yaml.safe_dump(doc, sort_keys=False, width=10**9))
        print(f"wrote {out.name}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--inject-hists":
        inject_hists(sys.argv[2])
    else:
        generate()
